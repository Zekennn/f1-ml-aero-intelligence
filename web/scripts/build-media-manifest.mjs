// Runs before every `next build` (the "prebuild" npm script).
//
// Writes data/media-manifest.json: the gallery photos in public/img (with their pixel sizes)
// and the file names in public/images/tracks and public/images/drivers.
//
// Why: on Vercel, pages rendered on request run as serverless functions, and files in public/
// are served from the CDN but are NOT inside those functions. Code that lists or checks files in
// public/ at request time (lib/media.ts, lib/gallery.ts) falls back to this manifest there.
// Locally the folders are read directly, so new photos show up without re-running this.
import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { imageSize } from "../lib/imageSize.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PUBLIC = path.join(ROOT, "public");
const IMAGE = /\.(jpe?g|png|webp)$/i;

async function list(sub) {
  try {
    return (await readdir(path.join(PUBLIC, sub))).filter((n) => IMAGE.test(n)).sort();
  } catch {
    return [];
  }
}

const galleryNames = await list("img");
const gallery = await Promise.all(
  galleryNames.map(async (name) => {
    const size = await imageSize(path.join(PUBLIC, "img", name)).catch(() => null);
    return { name, width: size?.width ?? 1080, height: size?.height ?? 1350 };
  }),
);

const manifest = {
  note: "Generated by scripts/build-media-manifest.mjs before each build. Do not edit.",
  gallery,
  "images/tracks": await list("images/tracks"),
  "images/drivers": await list("images/drivers"),
};

await writeFile(path.join(ROOT, "data", "media-manifest.json"), JSON.stringify(manifest, null, 2) + "\n", "utf-8");
console.log(
  `media manifest: ${gallery.length} gallery photos, ${manifest["images/tracks"].length} track images, ` +
    `${manifest["images/drivers"].length} driver photos`,
);
